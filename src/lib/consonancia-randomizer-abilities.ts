const randomizedAbilityPool = gameAbilityIds
  .trim()
  .split(/\s+/)
  .filter((ability) => !excludedAbilityIds.has(ability));

const mtSize = 624;
const mtOffset = 397;
const mtMatrixA = 0x9908b0df;

function createRubyRandom(seed: number) {
  const state = new Uint32Array(mtSize);
  state[0] = seed >>> 0;
  for (let index = 1; index < mtSize; index += 1) {
    const previous = state[index - 1];
    state[index] =
      (Math.imul(1812433253, previous ^ (previous >>> 30)) + index) >>> 0;
  }

  let index = mtSize;
  return {
    limited(maximum: number) {
      let mask = maximum >>> 0;
      mask |= mask >>> 1;
      mask |= mask >>> 2;
      mask |= mask >>> 4;
      mask |= mask >>> 8;
      mask |= mask >>> 16;

      while (true) {
        if (index >= mtSize) {
          for (let offset = 0; offset < mtSize; offset += 1) {
            const value =
              (state[offset] & 0x80000000) |
              (state[(offset + 1) % mtSize] & 0x7fffffff);
            state[offset] =
              state[(offset + mtOffset) % mtSize] ^
              (value >>> 1) ^
              ((value & 1) === 0 ? 0 : mtMatrixA);
          }
          index = 0;
        }

        let value = state[index];
        index += 1;
        value ^= value >>> 11;
        value ^= (value << 7) & 0x9d2c5680;
        value ^= (value << 15) & 0xefc60000;
        value ^= value >>> 18;
        value >>>= 0;

        const result = value & mask;
        if (result <= maximum) return result;
      }
    },
  };
}

function stableRubySeed(seed: number, key: string) {
  let hash = seed >>> 0;
  for (const byte of new TextEncoder().encode(key)) {
    hash = Math.imul(hash ^ byte, 16777619) >>> 0;
  }
  return hash;
}

export function getRandomizedAbility({
  seed,
  key,
  originalAbility,
}: {
  seed: number;
  key: string;
  originalAbility: string;
}) {
  if (randomizedAbilityPool.length === 0) {
    throw new Error("Consonancia randomizer ability pool is empty");
  }

  const abilitySeed = stableRubySeed(seed, key);
  const abilityIndex = createRubyRandom(abilitySeed).limited(
    randomizedAbilityPool.length - 1,
  );

  return randomizedAbilityPool[abilityIndex] ?? originalAbility;
}

export function getRandomizedAbilityPoolSize() {
  return randomizedAbilityPool.length;
}
